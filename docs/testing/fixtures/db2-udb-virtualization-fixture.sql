CONNECT TO FORGETDM;

CREATE SCHEMA FTDM_VIRT_DEMO AUTHORIZATION DB2INST1;
SET CURRENT SCHEMA FTDM_VIRT_DEMO;

DROP TABLE PAYMENT;
DROP TABLE ACCOUNT;
DROP TABLE CUSTOMER;

CREATE TABLE CUSTOMER (
    CUSTOMER_ID BIGINT NOT NULL,
    CUSTOMER_NO VARCHAR(24) NOT NULL,
    FULL_NAME VARCHAR(120) NOT NULL,
    EMAIL_ADDRESS VARCHAR(180),
    CUSTOMER_STATUS VARCHAR(16) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_VIRT_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UK_VIRT_CUSTOMER_NO UNIQUE (CUSTOMER_NO),
    CONSTRAINT CK_VIRT_CUSTOMER_STATUS CHECK (CUSTOMER_STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE ACCOUNT (
    ACCOUNT_ID BIGINT NOT NULL,
    CUSTOMER_ID BIGINT NOT NULL,
    ACCOUNT_NO VARCHAR(32) NOT NULL,
    ACCOUNT_TYPE VARCHAR(20) NOT NULL,
    BALANCE DECIMAL(15,2) NOT NULL,
    OPENED_ON DATE NOT NULL,
    CONSTRAINT PK_VIRT_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UK_VIRT_ACCOUNT_NO UNIQUE (ACCOUNT_NO),
    CONSTRAINT FK_VIRT_ACCOUNT_CUSTOMER FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID)
);

CREATE TABLE PAYMENT (
    PAYMENT_ID BIGINT NOT NULL,
    ACCOUNT_ID BIGINT NOT NULL,
    PAYMENT_REF VARCHAR(32) NOT NULL,
    AMOUNT DECIMAL(15,2) NOT NULL,
    PAYMENT_STATUS VARCHAR(16) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_VIRT_PAYMENT PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT UK_VIRT_PAYMENT_REF UNIQUE (PAYMENT_REF),
    CONSTRAINT FK_VIRT_PAYMENT_ACCOUNT FOREIGN KEY (ACCOUNT_ID)
        REFERENCES ACCOUNT (ACCOUNT_ID)
);

INSERT INTO CUSTOMER (CUSTOMER_ID, CUSTOMER_NO, FULL_NAME, EMAIL_ADDRESS, CUSTOMER_STATUS)
WITH N (ID) AS (
    VALUES BIGINT(1)
    UNION ALL
    SELECT ID + 1 FROM N WHERE ID < 40
)
SELECT ID,
       'CUST-' || DIGITS(DECIMAL(ID, 5, 0)),
       'Virtual Customer ' || RTRIM(CHAR(ID)),
       'virtual.customer' || RTRIM(CHAR(ID)) || '@example.test',
       CASE WHEN MOD(ID, 9) = 0 THEN 'INACTIVE' ELSE 'ACTIVE' END
FROM N;

INSERT INTO ACCOUNT (ACCOUNT_ID, CUSTOMER_ID, ACCOUNT_NO, ACCOUNT_TYPE, BALANCE, OPENED_ON)
WITH N (ID) AS (
    VALUES BIGINT(1)
    UNION ALL
    SELECT ID + 1 FROM N WHERE ID < 80
)
SELECT ID,
       BIGINT(1 + MOD(ID - 1, 40)),
       'AC' || DIGITS(DECIMAL(ID, 12, 0)),
       CASE WHEN MOD(ID, 2) = 0 THEN 'CHECKING' ELSE 'SAVINGS' END,
       DECIMAL(ID * 137.25, 15, 2),
       DATE('2024-01-01') + INTEGER(MOD(ID, 365)) DAYS
FROM N;

INSERT INTO PAYMENT (PAYMENT_ID, ACCOUNT_ID, PAYMENT_REF, AMOUNT, PAYMENT_STATUS)
WITH N (ID) AS (
    VALUES BIGINT(1)
    UNION ALL
    SELECT ID + 1 FROM N WHERE ID < 240
)
SELECT ID,
       BIGINT(1 + MOD(ID - 1, 80)),
       'PAY-' || DIGITS(DECIMAL(ID, 12, 0)),
       DECIMAL(10 + MOD(ID * 17, 9000) / 10.0, 15, 2),
       CASE WHEN MOD(ID, 11) = 0 THEN 'PENDING' ELSE 'SETTLED' END
FROM N;

COMMIT;

SELECT 'CUSTOMER' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM CUSTOMER
UNION ALL
SELECT 'ACCOUNT', COUNT(*) FROM ACCOUNT
UNION ALL
SELECT 'PAYMENT', COUNT(*) FROM PAYMENT
ORDER BY TABLE_NAME;

CONNECT RESET;
